import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import { datasheets } from '../src/data/datasheets.js';
const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
test('directory search, category filters and empty state', async ({page}) => {
    await page.goto('/datasheets.html');
    await expect(page.locator('[data-document]:visible')).toHaveCount(12);
    await page.getByRole('button', {name:'Series datasheets',exact:true}).click();
    await expect(page.locator('[data-document]:visible')).toHaveCount(2);
    await page.locator('#datasheet-search').fill('N-035-0496');
    await expect(page.locator('[data-document]:visible')).toHaveCount(1);
    await expect(page.locator('[data-document]:visible')).toContainText('A20');
    await page.locator('#datasheet-search').fill('no-such-component');
    await expect(page.locator('#datasheet-empty')).toBeVisible();
    await page.locator('#reset-datasheet-filters').click();
    await expect(page.locator('[data-document]:visible')).toHaveCount(12);
    await page.locator('#datasheet-search').fill('support');
    await expect(page.locator('[data-document]:visible')).toHaveCount(4);
});
test('all twelve previews render all pages, both downloads preserve original bytes and names', async ({page}) => {
    test.setTimeout(180_000);
    const errors=[];page.on('pageerror', error=>errors.push(error.message));
    await page.goto('/datasheets.html');
    for(const doc of datasheets){
        const original=await fs.readFile(`assets/datasheets/${doc.filename}`);
        const response=await page.request.get(doc.url);
        expect(response.ok()).toBeTruthy();expect(digest(await response.body())).toBe(digest(original));
        const directoryDownload=page.waitForEvent('download');
        await page.locator(`[data-download="${doc.id}"]`).click();
        const dl=await directoryDownload;
        expect(dl.suggestedFilename()).toBe(doc.filename);
        expect(digest(await fs.readFile(await dl.path()))).toBe(digest(original));
        await page.locator(`[data-view="${doc.id}"]`).click();
        await expect(page.locator('#pdf-modal')).toBeVisible();
        await expect(page.locator('#pdf-modal-title')).toHaveText(doc.title);
        await expect(page.locator('#pdf-pages canvas')).toHaveCount(doc.pages);
        await expect(page.locator('#pdf-scroll')).toHaveAttribute('aria-busy','false');
        await expect(page.locator('#pdf-print')).toBeEnabled();
        const frameBytes=await page.locator('.pdf-print-frame').evaluate(async frame=>Array.from(new Uint8Array(await (await fetch(frame.src)).arrayBuffer())));
        expect(digest(new Uint8Array(frameBytes))).toBe(digest(original));
        const modalDownload=page.waitForEvent('download');
        await page.locator('#pdf-download').click();
        const mdl=await modalDownload;
        expect(mdl.suggestedFilename()).toBe(doc.filename);
        expect(digest(await fs.readFile(await mdl.path()))).toBe(digest(original));
        await page.locator('#pdf-close').click();
        await expect(page.locator('#pdf-modal')).not.toBeVisible();
        await expect(page.locator(`[data-view="${doc.id}"]`)).toBeFocused();
        await expect(page.locator('.pdf-print-frame')).toHaveCount(0);
    }
    expect(errors).toEqual([]);
});
test('modal keyboard, backdrop, fit, zoom, scroll and print target',async({page})=>{
    await page.goto('/datasheets.html');
    await page.locator('[data-view="a20"]').click();
    await expect(page.locator('#pdf-pages canvas')).toHaveCount(2);
    await expect(page.locator('#pdf-close')).toBeFocused();
    expect(await page.evaluate(()=>document.body.style.position)).toBe('fixed');
    await page.locator('#pdf-scroll').focus();await page.keyboard.press('Tab');
    await expect(page.locator('#pdf-print')).toBeFocused();
    await page.keyboard.press('Shift+Tab');await expect(page.locator('#pdf-scroll')).toBeFocused();
    const before=await page.locator('#pdf-pages canvas').first().boundingBox();
    await page.locator('#pdf-zoom-in').click();
    await expect(page.locator('#pdf-zoom-label')).toHaveText('125%');
    expect((await page.locator('#pdf-pages canvas').first().boundingBox()).width).toBeGreaterThan(before.width);
    await page.locator('#pdf-fit').click();await expect(page.locator('#pdf-zoom-label')).toHaveText('Fit');
    // Verify print() is invoked on the original-PDF frame, never on the website window.
    await page.locator('.pdf-print-frame').evaluate(frame=>{frame.contentWindow.print=()=>{frame.dataset.printed='true';};});
    await page.locator('#pdf-print').click();
    await expect(page.locator('.pdf-print-frame')).toHaveAttribute('data-printed','true');
    await page.keyboard.press('Escape');await expect(page.locator('#pdf-modal')).not.toBeVisible();
    expect(await page.evaluate(()=>document.body.style.position)).toBe('');
    await page.locator('[data-view="a30"]').click();
    await expect(page.locator('#pdf-pages canvas')).toHaveCount(2);
    await page.locator('#pdf-modal-title').click();await expect(page.locator('#pdf-modal')).toBeVisible();
    await page.mouse.click(10,500);await expect(page.locator('#pdf-modal')).not.toBeVisible();
});
test('failed requests show error and recover on retry',async({page})=>{
    await page.goto('/datasheets.html');
    await page.route('**/assets/datasheets/**',route=>route.fulfill({status:503,body:'Unavailable'}));
    await page.locator('[data-view="a20"]').click();
    await expect(page.locator('#pdf-status')).toContainText('preview could not load');
    await expect(page.locator('#pdf-print')).toBeDisabled();
    await page.locator('#pdf-download').click();await expect(page.locator('#pdf-status')).toContainText('Download could not start');
    await page.unroute('**/assets/datasheets/**');
    await page.locator('#pdf-close').click();await page.locator('[data-view="a20"]').click();
    await expect(page.locator('#pdf-pages canvas')).toHaveCount(2);
});
